#ifndef DRV8313_HANDLE_H_
#define DRV8313_HANDLE_H_

/*********************************************************************************************************************/
/*-----------------------------------------------------Includes------------------------------------------------------*/
/*********************************************************************************************************************/

#include "Ifx_Types.h"
#include "IfxPort.h"

/*********************************************************************************************************************/
/*------------------------------------------------------Macros-------------------------------------------------------*/
/*********************************************************************************************************************/

/*
 * 修改为你的实际 TC375 引脚。
 *
 * nRT:    nRESET，低电平有效
 * nSP:    nSLEEP，低电平有效
 * nFT:    nFAULT，低电平有效
 */

/* DRV8313 nRESET pin */
#define DRV8313_NRT_PORT              (&MODULE_P33)
#define DRV8313_NRT_PIN               (11U)

/* DRV8313 nSLEEP pin */
#define DRV8313_NSP_PORT              (&MODULE_P33)
#define DRV8313_NSP_PIN               (12U)

/* DRV8313 nFAULT pin */
#define DRV8313_NFT_PORT              (&MODULE_P33)
#define DRV8313_NFT_PIN               (13U)

/* Pin logic levels */
#define DRV8313_PIN_HIGH              (TRUE)
#define DRV8313_PIN_LOW               (FALSE)

/*********************************************************************************************************************/
/*-------------------------------------------------Global variables--------------------------------------------------*/
/*********************************************************************************************************************/

/*********************************************************************************************************************/
/*-------------------------------------------------Data Structures---------------------------------------------------*/
/*********************************************************************************************************************/

typedef enum
{
    DRV8313_STATUS_DISABLED = 0,
    DRV8313_STATUS_READY,
    DRV8313_STATUS_FAULT
} Drv8313_Status;

/*********************************************************************************************************************/
/*--------------------------------------------Private Variables/Constants--------------------------------------------*/
/*********************************************************************************************************************/

/*********************************************************************************************************************/
/*------------------------------------------------Function Prototypes------------------------------------------------*/
/*********************************************************************************************************************/

/**
 * @brief Initialize the DRV8313 control and fault GPIO pins.
 *
 * nRESET and nSLEEP are configured as push-pull outputs.
 * nFAULT is configured as an input with pull-up.
 *
 * After initialization, the driver remains disabled.
 */
void Drv8313_init(void);

/**
 * @brief Enable the DRV8313.
 *
 * Releases nSLEEP and nRESET.
 */
void Drv8313_enable(void);

/**
 * @brief Disable the DRV8313.
 *
 * Pulls nRESET and nSLEEP low.
 */
void Drv8313_disable(void);

/**
 * @brief Reset the DRV8313 fault state.
 *
 * Generates a low pulse on nRESET.
 */
void Drv8313_reset(void);

/**
 * @brief Read the nFAULT signal.
 *
 * @return TRUE if a fault is active.
 * @return FALSE if no fault is active.
 */
boolean Drv8313_hasFault(void);

/**
 * @brief Get the current DRV8313 status.
 *
 * @return Current driver status.
 */
Drv8313_Status Drv8313_getStatus(void);

#endif /* DRV8313_HANDLE_H_ */
